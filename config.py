"""Конфигурация бота и упражнения."""
import os
from dataclasses import dataclass
from typing import Dict, List


@dataclass
class Config:
    """Конфигурация бота."""
    BOT_TOKEN: str
    PORT: int = 10000
    WEBHOOK_URL: str = ""
    
    @classmethod
    def from_env(cls) -> "Config":
        """Создать конфигурацию из переменных окружения."""
        token = os.getenv("BOT_TOKEN", "").strip()
        if not token or token.startswith("вставь"):
            raise ValueError("BOT_TOKEN не найден или не заполнен в переменных окружения")
        
        port = int(os.getenv("PORT", "10000"))
        webhook_url = os.getenv("WEBHOOK_URL", "")
        
        return cls(BOT_TOKEN=token, PORT=port, WEBHOOK_URL=webhook_url)


